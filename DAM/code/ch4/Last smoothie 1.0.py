#Declaramos la lista de los posibles sabores de "smoothies"
smoothies = ['coconut', 'strawberry', 'banana', 'tropical', 'acai berry']

#Usamos la función len para saber cuántos tipos de sabor tenemos
lenght = len(smoothies)

#Metemos en la variable last el nombre del último sabor (el que ocupa la posición lenght-1)
last = smoothies[lenght-1]

#Imprimimos el último sabor de smoothie.
print(last)
